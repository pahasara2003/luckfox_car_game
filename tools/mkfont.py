#!/usr/bin/env python3
"""
mkfont.py - Generate C++ font header for Inter font glyphs (ASCII 32..126)
for use in the luckfox_car_game HUD rasterizer.
"""

import sys
import os
from PIL import ImageFont

FONT_DIR = "/usr/share/fonts/rsms-inter-fonts"

FONTS = [
    {
        "name": "fontSmall",
        "file": os.path.join(FONT_DIR, "Inter-Bold.ttf"),
        "size": 11,
    },
    {
        "name": "fontMedium",
        "file": os.path.join(FONT_DIR, "Inter-Bold.ttf"),
        "size": 15,
    },
    {
        "name": "fontLarge",
        "file": os.path.join(FONT_DIR, "Inter-Bold.ttf"),
        "size": 24,
    },
    {
        "name": "fontHuge",
        "file": os.path.join(FONT_DIR, "Inter-ExtraBold.ttf"),
        "size": 36,
    },
]

def generate_header(out_path):
    out = []
    out.append("// Generated by tools/mkfont.py - DO NOT EDIT MANUALLY")
    out.append("#ifndef FONT_HUD_H")
    out.append("#define FONT_HUD_H\n")
    out.append("#include <cstdint>")
    out.append("#include <cstddef>\n")
    out.append("struct HudGlyph {")
    out.append("    uint8_t w, h;       // dimensions of alpha mask")
    out.append("    int8_t left, top;   // bearing relative to top-left of line")
    out.append("    uint8_t advance;    // cursor x advance")
    out.append("    uint32_t offset;    // byte offset into font bitmaps")
    out.append("};\n")
    out.append("struct HudFont {")
    out.append("    uint8_t ascent;")
    out.append("    uint8_t descent;")
    out.append("    uint8_t line_height;")
    out.append("    const HudGlyph* glyphs; // ASCII 32..126 (length 95)")
    out.append("    const uint8_t* bitmaps;")
    out.append("};\n")

    for f_info in FONTS:
        name = f_info["name"]
        font = ImageFont.truetype(f_info["file"], f_info["size"])
        ascent, descent = font.getmetrics()
        line_height = ascent + descent

        bitmap_bytes = bytearray()
        glyphs = []

        for cp in range(32, 127):
            ch = chr(cp)
            mask = font.getmask(ch, mode='L')
            bbox = font.getbbox(ch)
            w, h = mask.size
            if w > 0 and h > 0:
                left = bbox[0]
                top = bbox[1]
                # steepen the anti-aliasing ramp: a one-pixel soft edge stays crisp on the 320x240 panel
                data = bytes(max(0, min(255, (v - 60) * 255 // 140)) for v in bytes(mask))
                offset = len(bitmap_bytes)
                bitmap_bytes.extend(data)
            else:
                left = 0
                top = 0
                offset = 0
            adv = max(0, min(255, int(round(font.getlength(ch)))))
            glyphs.append((w, h, left, top, adv, offset))

        # Format bitmaps array
        out.append(f"// Bitmaps for {name} ({len(bitmap_bytes)} bytes)")
        out.append(f"static const uint8_t {name}_bitmaps[{max(1, len(bitmap_bytes))}] = {{")
        line = []
        for i, b in enumerate(bitmap_bytes):
            line.append(f"0x{b:02x}")
            if len(line) == 16:
                out.append("    " + ", ".join(line) + ",")
                line = []
        if line:
            out.append("    " + ", ".join(line) + ",")
        out.append("};\n")

        # Format glyphs array
        out.append(f"// Glyphs for {name} (ASCII 32..126)")
        out.append(f"static const HudGlyph {name}_glyphs[95] = {{")
        for cp in range(32, 127):
            ch = chr(cp)
            w, h, left, top, adv, offset = glyphs[cp - 32]
            comment = f"/* '{ch}' (32) */" if ch == ' ' else f"/* '{ch}' */"
            out.append(f"    {{{w}, {h}, {left}, {top}, {adv}, {offset}}}, {comment}")
        out.append("};\n")

        # Format HudFont instance
        out.append(f"static const HudFont {name} = {{")
        out.append(f"    {ascent}, {descent}, {line_height},")
        out.append(f"    {name}_glyphs,")
        out.append(f"    {name}_bitmaps")
        out.append("};\n")

    out.append("#endif // FONT_HUD_H\n")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"Generated {out_path} successfully.")

if __name__ == "__main__":
    out_file = sys.argv[1] if len(sys.argv) > 1 else "src/font_hud.h"
    generate_header(out_file)
